#!/usr/bin/env node
/**
 * trim-bootstrap.mjs
 *
 * Writes styles/bootstrap.trimmed.css: Bootstrap's compiled CSS with every
 * rule removed whose selectors need a class the site never uses.
 *
 * Why: the full bootstrap.min.css (230 KB, 31 KB gzipped) is render-blocking
 * on every page, and the site uses ~5% of its classes (SEO audit, Oct 2026).
 *
 * Safety: "used" means the class name appears ANYWHERE as a word in app/,
 * components/, lib/, hooks/ or public/data/ — over-inclusive by design, so a
 * rule is only dropped when nothing could possibly reference it. Classes that
 * Bootstrap's own JS adds at runtime are always kept. Element, :root and
 * reboot rules (no class in the selector) are always kept.
 *
 * Runs in predev and prebuild, so a newly used Bootstrap class is picked up
 * automatically. Do not edit the output file by hand.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve, dirname, extname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "node_modules/bootstrap/dist/css/bootstrap.min.css");
const OUT = join(ROOT, "styles/bootstrap.trimmed.css");
const SCAN = ["app", "components", "lib", "hooks", "public/data"];
const EXTS = new Set([".js", ".jsx", ".mjs", ".ts", ".tsx", ".json", ".css"]);
// Added by bootstrap/js/dist/collapse.js and friends at runtime.
const RUNTIME = ["collapse", "collapsing", "collapsed", "show", "collapse-horizontal", "fade", "active", "disabled"];

const used = new Set(RUNTIME);
function walk(dir) {
  let entries;
  try { entries = readdirSync(dir); } catch { return; }
  for (const e of entries) {
    const full = join(dir, e);
    if (statSync(full).isDirectory()) { if (e !== "node_modules") walk(full); continue; }
    if (!EXTS.has(extname(e))) continue;
    for (const w of readFileSync(full, "utf8").match(/[A-Za-z0-9_-]+/g) || []) used.add(w);
  }
}
for (const d of SCAN) walk(join(ROOT, d));

const css = readFileSync(SRC, "utf8");

// Minimal CSS walker for minified Bootstrap: top-level rules, @media/@supports
// blocks (recursed), and other at-rules (@keyframes etc.) kept verbatim.
function parse(text) {
  const out = [];
  let i = 0;
  while (i < text.length) {
    if (text.startsWith("/*", i)) {           // keep the license banner
      const end = text.indexOf("*/", i) + 2;
      out.push({ type: "comment", text: text.slice(i, end) }); i = end; continue;
    }
    const open = text.indexOf("{", i);
    if (open < 0) break;
    const prelude = text.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (depth && j < text.length) { if (text[j] === "{") depth++; else if (text[j] === "}") depth--; j++; }
    const body = text.slice(open + 1, j - 1);
    if (/^@(media|supports|container|layer)\b/.test(prelude)) out.push({ type: "group", prelude, children: parse(body) });
    else if (prelude.startsWith("@")) out.push({ type: "at", text: text.slice(i, j) });
    else out.push({ type: "rule", prelude, body });
    i = j;
  }
  return out;
}

function splitSelectors(sel) {             // split on top-level commas only
  const parts = []; let depth = 0, cur = "";
  for (const ch of sel) {
    if (ch === "(" || ch === "[") depth++;
    if (ch === ")" || ch === "]") depth--;
    if (ch === "," && depth === 0) { parts.push(cur); cur = ""; } else cur += ch;
  }
  parts.push(cur); return parts;
}
function partNeeded(part) {
  // Classes inside :not()/:is()/:where()/:has() are conditions, not requirements.
  let p = part, prev;
  do { prev = p; p = p.replace(/:(not|is|where|has)\((?:[^()]|\([^()]*\))*\)/g, ""); } while (p !== prev);
  const classes = p.match(/\.(-?[_a-zA-Z][\w-]*)/g) || [];
  return classes.every((c) => used.has(c.slice(1)));
}
let kept = 0, dropped = 0;
function emit(nodes) {
  let s = "";
  for (const n of nodes) {
    if (n.type === "comment" || n.type === "at") { s += n.text; continue; }
    if (n.type === "group") { const inner = emit(n.children); if (inner) s += `${n.prelude}{${inner}}`; continue; }
    const parts = splitSelectors(n.prelude).filter(partNeeded);
    if (parts.length) { s += `${parts.join(",")}{${n.body}}`; kept++; } else dropped++;
  }
  return s;
}
const result = emit(parse(css));
writeFileSync(OUT, `/* GENERATED by scripts/trim-bootstrap.mjs from bootstrap.min.css — do not edit. */\n${result}\n`);
console.log(`bootstrap trim: kept ${kept} rules, dropped ${dropped} — ${(css.length / 1024).toFixed(0)} KB → ${(result.length / 1024).toFixed(0)} KB`);
